import { DEFAULT_DOMAIN_RECORDS, type DomainRecord } from '@internal/disposable-email-core'

export interface SupabaseMigrationOptions {
  schema?: string
  table?: string
  functionName?: string
}

const IDENTIFIER_PATTERN = /^[a-z_][a-z0-9_]{0,62}$/

function identifier(value: string, label: string): string {
  if (!IDENTIFIER_PATTERN.test(value)) {
    throw new TypeError(`${label} must be a lowercase SQL identifier`)
  }
  return value
}

function sqlString(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}

function sqlTextArray(values: readonly string[]): string {
  return `ARRAY[${values.map(sqlString).join(', ')}]::text[]`
}

function seedSql(records: readonly DomainRecord[]): string {
  const blockable = records.filter(
    (record) =>
      record.status === 'active' &&
      record.classification === 'disposable' &&
      (record.confidence === 'medium' || record.confidence === 'high')
  )
  return blockable
    .map(
      (record) =>
        `  (${sqlString(record.domain)}, ${sqlString(record.classification)}, ${sqlString(record.confidence)}, ${sqlTextArray(record.source_urls)}, ${sqlString(record.last_verified)}, ${record.block_subdomains}, ${sqlString(record.status)})`
    )
    .join(',\n')
}

export function renderSupabaseMigration(
  records: readonly DomainRecord[] = DEFAULT_DOMAIN_RECORDS,
  options: SupabaseMigrationOptions = {}
): string {
  const schema = identifier(options.schema ?? 'disposable_email_guard', 'schema')
  const table = identifier(options.table ?? 'blocked_signup_email_domains', 'table')
  const functionName = identifier(
    options.functionName ?? 'before_user_created_email_guard',
    'functionName'
  )
  const fqTable = `${schema}.${table}`
  const fqFunction = `${schema}.${functionName}`
  const seeds = seedSql(records)
  const seedInsert = seeds
    ? `values\n${seeds}`
    : `select domain, classification, confidence, source_urls, last_verified, block_subdomains, status
from (values
  (null::text, null::text, null::text, null::text[], null::date, null::boolean, null::text)
) as empty_seed(domain, classification, confidence, source_urls, last_verified, block_subdomains, status)
where false`

  return `-- Generated by Disposable Email Domain Blocklist. Review before applying.
-- This file only creates SQL; it never connects to a Supabase project.
create schema if not exists ${schema};

revoke all on schema ${schema} from public, anon, authenticated;
grant usage on schema ${schema} to supabase_auth_admin;

create table if not exists ${fqTable} (
  domain text primary key,
  classification text not null check (classification in ('disposable', 'alias', 'role', 'free_provider', 'unknown')),
  confidence text not null check (confidence in ('low', 'medium', 'high')),
  source_urls text[] not null default '{}',
  last_verified date not null,
  block_subdomains boolean not null default true,
  status text not null check (status in ('active', 'stale', 'disputed', 'removed')),
  created_at timestamptz not null default now()
);

alter table ${fqTable} enable row level security;
revoke all on table ${fqTable} from public, anon, authenticated;
grant select on table ${fqTable} to supabase_auth_admin;
drop policy if exists ${table}_auth_admin_read on ${fqTable};
create policy ${table}_auth_admin_read
  on ${fqTable}
  for select
  to supabase_auth_admin
  using (true);

insert into ${fqTable}
  (domain, classification, confidence, source_urls, last_verified, block_subdomains, status)
${seedInsert}
on conflict (domain) do update
set
  classification = excluded.classification,
  confidence = excluded.confidence,
  source_urls = excluded.source_urls,
  last_verified = excluded.last_verified,
  block_subdomains = excluded.block_subdomains,
  status = excluded.status;

create or replace function ${fqFunction}(event jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  email_value text := lower(btrim(coalesce(event -> 'user' ->> 'email', '')));
  email_domain text;
  at_sign_count integer;
begin
  if email_value = '' then
    return '{}'::jsonb;
  end if;

  at_sign_count := length(email_value) - length(replace(email_value, '@', ''));
  email_domain := split_part(email_value, '@', 2);

  if length(email_value) > 254
     or at_sign_count <> 1
     or split_part(email_value, '@', 1) = ''
     or length(email_domain) > 253
     or email_domain !~ '^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$'
     or exists (
       select 1
       from ${fqTable} as blocked
       where blocked.status = 'active'
         and blocked.classification = 'disposable'
         and blocked.confidence in ('medium', 'high')
         and (
           email_domain = blocked.domain
           or (blocked.block_subdomains and email_domain like '%.' || blocked.domain)
         )
     ) then
    return jsonb_build_object(
      'error', jsonb_build_object(
        'http_code', 400,
        'message', 'SIGNUP_EMAIL_NOT_ALLOWED'
      )
    );
  end if;

  return '{}'::jsonb;
end;
$$;

revoke all on function ${fqFunction}(jsonb) from public, anon, authenticated;
grant execute on function ${fqFunction}(jsonb) to supabase_auth_admin;

comment on table ${fqTable} is
  'Private evidence-backed dataset used by the Before User Created Auth Hook.';
comment on function ${fqFunction}(jsonb) is
  'Rejects malformed and default-blockable disposable email domains before user creation.';
`
}
