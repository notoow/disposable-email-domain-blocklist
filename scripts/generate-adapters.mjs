import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '..')
const canonical = await readFile(resolve(root, 'agent-integration/instructions.md'), 'utf8')
const hash = createHash('sha256').update(canonical).digest('hex')

const codex = `---
name: disposable-email-blocklist
description: Apply the evidence-backed Disposable Email Domain Blocklist workflow at a server or database signup boundary.
---

<!-- Generated from agent-integration/instructions.md; canonical_sha256=${hash} -->

${canonical}`

const claude = `---
name: disposable-email-blocklist
description: Apply evidence-backed disposable email blocking safely at the server or database signup boundary.
---

<!-- Generated from agent-integration/instructions.md; canonical_sha256=${hash} -->

${canonical}`

const cursor = `---
description: Evidence-backed disposable email blocking at signup boundaries
globs:
  - "**/*auth*"
  - "**/*signup*"
alwaysApply: false
---

<!-- Generated from agent-integration/instructions.md; canonical_sha256=${hash} -->

${canonical}`

const generatedSource = `// Generated by scripts/generate-adapters.mjs. Do not edit.\nexport const AGENT_ADAPTERS = ${JSON.stringify(
  {
    codex: { relativePath: '.codex/skills/disposable-email-blocklist/SKILL.md', content: codex },
    claude: { relativePath: '.claude/skills/disposable-email-blocklist/SKILL.md', content: claude },
    cursor: { relativePath: '.cursor/rules/disposable-email-blocklist.mdc', content: cursor },
  },
  null,
  2
)} as const\nexport const CANONICAL_INSTRUCTIONS_SHA256 = '${hash}'\n`

const artifacts = {
  'adapters/agents/codex/SKILL.md': codex,
  'adapters/agents/claude/SKILL.md': claude,
  'adapters/agents/cursor/disposable-email-blocklist.mdc': cursor,
  'cli/src/generated/adapters.ts': generatedSource,
}

for (const [relativePath, content] of Object.entries(artifacts)) {
  await writeFile(resolve(root, relativePath), content, 'utf8')
}
console.log(`Generated ${Object.keys(artifacts).length} agent adapter artifacts (sha256=${hash}).`)

